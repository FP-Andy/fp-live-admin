import assert from 'node:assert/strict';
import {mapCourt,mapPoint,directionHandle,pickMap,targetMarker} from '../../apps/web/public/kbl-grayzone/scene-map.mjs';
import {cornerJoinX,COURT} from '../../apps/web/public/kbl-grayzone/court-asset.mjs';
import {progress,nextIncomplete} from '../../apps/web/public/kbl-grayzone/flow-progress.mjs';
const bottom={id:'ref',x:5.7,y:15.4,bodyHeading:0};
const roundTrip=mapCourt(mapPoint(bottom));
assert.deepEqual(targetMarker(bottom),mapPoint(bottom));
assert.ok(Math.abs(roundTrip.x-bottom.x)<1e-10 && Math.abs(roundTrip.y-bottom.y)<1e-10);
assert.equal(pickMap([bottom],mapPoint(bottom),.4)?.id,'ref');
assert.equal(pickMap([bottom],[0,0]),null);
assert.equal(pickMap([bottom,{...bottom,id:'other'}],mapPoint(bottom),1,'ref').id,'other');
const [x,y]=mapPoint(bottom),[hx,hy]=directionHandle({...bottom,viewHeading:Math.PI/2});
assert.ok(Math.abs(hx-x)<1e-10 && Math.abs(hy-y-64)<1e-10);
assert.ok(cornerJoinX>2.9 && cornerJoinX<3.1);
assert.ok(Math.abs(Math.hypot(cornerJoinX-COURT.basketX,7.5-COURT.cornerY)-6.75)<1e-10);
const events=Array.from({length:4},(_,i)=>({id:i,stages:Object.fromEntries(['objects','joints','spatial'].map(s=>[s,{complete:i===0}]))}));
assert.deepEqual(progress(events),{total:4,objects:1,joints:1,spatial:1});
assert.equal(nextIncomplete(events).id,1);
console.log('Court corners, off-court referee selection, direction and 1/4 progress passed.');
