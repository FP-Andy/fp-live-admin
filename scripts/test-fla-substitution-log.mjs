import assert from 'node:assert/strict';
import {createSubstitutionLog,validateSubstitutionLog,saveSubstitution,removeSubstitution,activePlayersAt,buildAppearanceIntervals,exportSubstitutionLog,substitutionCsv,appearancesCsv,parseLogTime,formatLogTime} from '../apps/web/public/fla-video/substitution-log.mjs';
const context={name:'queen.mp4',duration:300,from:100,to:200};
const base={schema:'fpa-substitution-log/v1',video:context,players:[{id:'a',team:'home',name:'선발 A',jersey:'7'},{id:'b',team:'home',name:'교체 B',jersey:'8'},{id:'c',team:'home',name:'선발 C',jersey:'9'},{id:'d',team:'home',name:'교체 D',jersey:'10'},{id:'z',team:'away',name:'원정 Z',jersey:'7'}],initialPlayers:['a','c','z'],substitutions:[]};
const change=(id,time,outId,inId)=>({id,time,team:'home',outId,inId,note:''});
let log=saveSubstitution(base,change('s1',120.125,'a','b'));
log=saveSubstitution(log,change('s2',170.5,'b','a'));
const original=JSON.stringify(log), intervals=buildAppearanceIntervals(log);
assert.deepEqual(intervals.filter(p=>p.id==='a').map(p=>[p.from,p.to,p.stint]),[[100,120.125,1],[170.5,200,2]],'Returning player keeps one ID and separate stints');
assert.equal(intervals.filter(p=>p.id==='b')[0].videoSeconds,50.375);
assert.equal(intervals.reduce((n,p)=>n+p.videoSeconds,0),300,'No lost or doubled person-time');
assert.deepEqual([...activePlayersAt(log,120.125)],['c','z','b']);
assert(activePlayersAt(log,120.125,true).has('a'),'Boundary is half-open, OUT is active before the exchange');
assert.equal(JSON.stringify(log),original);
assert.equal(base.substitutions.length,0,'Edits never mutate the prior log');
assert.throws(()=>saveSubstitution(log,change('same',180,'a','a')),/서로 다른/);
assert.throws(()=>saveSubstitution(log,change('bench',180,'b','d')),/출전 중이 아닙니다/);
assert.throws(()=>saveSubstitution(log,change('active',180,'a','c')),/이미 출전 중/);
assert.throws(()=>saveSubstitution(log,change('team',180,'a','z')),/같은 팀/);
assert.throws(()=>saveSubstitution(log,change('range',99,'a','d')),/영상 구간/);
assert.throws(()=>saveSubstitution(log,change('range',200,'a','d')),/영상 구간/);
assert.throws(()=>saveSubstitution(log,change('duplicate-time',120.125,'b','a')),/동일 시각/);
assert.throws(()=>removeSubstitution(log,'s1'),/출전 중이 아닙니다/,'Deleting a prerequisite cannot silently corrupt reentry');
const simultaneous=saveSubstitution(log,change('other',120.125,'c','d'));
assert.equal(simultaneous.substitutions.length,3,'Independent simultaneous exchanges are accepted');
assert.equal(buildAppearanceIntervals(simultaneous).reduce((n,p)=>n+p.videoSeconds,0),300);
const edited=saveSubstitution(log,change('s1',130,'a','b'));
assert.equal(edited.substitutions.length,2);assert.equal(buildAppearanceIntervals(edited).find(p=>p.id==='b').videoSeconds,40.5);
assert.equal(removeSubstitution(log,'s2').substitutions.length,1);
assert.throws(()=>validateSubstitutionLog({...base,players:[...base.players,{id:'q',team:'home',name:'복제',jersey:'07'}]}),/등번호가 중복/);
assert.throws(()=>validateSubstitutionLog({...base,initialPlayers:['a','a']}),/시작 출전/);
assert.throws(()=>validateSubstitutionLog({...base,substitutions:[null]}),/교체 시각/);
assert.throws(()=>validateSubstitutionLog(log,{...context,from:0}),/다른 타임로그/);
assert.throws(()=>validateSubstitutionLog(log,{...context,name:'other.mp4'}),/다른 타임로그/);
assert.equal(parseLogTime('01:02:03.125'),3723.125);assert.equal(parseLogTime('120.125'),120.125);assert.equal(parseLogTime('02:00.125'),120.125);
for(const invalid of ['',' ','-1','1:60','1:60:00','NaN','Infinity'])assert.throws(()=>parseLogTime(invalid));
assert.equal(formatLogTime(59.9996),'01:00.000','Rounding carries to minutes');
const injection=saveSubstitution(base,{...change('csv',120,'a','b'),note:'=SUM(1,2)\n"메모"'});
assert(substitutionCsv(injection).startsWith('\ufeff'));assert.match(substitutionCsv(injection),/"'=SUM\(1,2\)\n""메모"""/);
assert.match(appearancesCsv(log),/"170.5","200","29.5"/);
const exported=exportSubstitutionLog(log);assert.equal(exported.trackingApplied,false);assert.equal(exported.clockBasis,'source-video-seconds');
assert.deepEqual(validateSubstitutionLog(JSON.parse(JSON.stringify(exported))).substitutions,log.substitutions);
console.log('PASS: reentry, simultaneous exchanges, interval boundaries, timeline validation, edit/delete and CSV escaping.');
