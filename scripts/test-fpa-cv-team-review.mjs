import assert from 'node:assert/strict';
import {validateDataset,emptyReview,assign,trackRange,validateReview,identityAt} from '../apps/web/public/fpa-cv/core.mjs';
import {reconnect} from '../apps/web/public/fpa-cv/identity.mjs';
import {uniformTimeline,effectiveSegments} from '../apps/web/public/fpa-cv/integrity.mjs';
import {classifyUniform} from '../apps/web/public/fpa-cv/colors.mjs';
import {lockedTeamConflicts,releaseTeamConflicts,confirmScene,clearScenes} from '../apps/web/public/fpa-cv/team-review.mjs';
import {packRecovery,hydrateRecovery} from '../apps/web/public/fpa-cv/recovery-protocol.mjs';

const uniforms={home_gk:[[240,170,10]],home:[[210,30,30]],referee:[[230,240,150]],away:[[30,100,230]],away_gk:[[30,220,140]]};
const roster=emptyReview({datasetId:'team-review'}).roster.map((p,i)=>({...p,jersey:p.group==='referee'?'REF':String(i)}));
const frames=Array.from({length:60},(_,i)=>({t:i/10,boxes:roster.flatMap((p,k)=>{
  if(k===7&&i>=20)return [];
  const x=.05+(k%7)*.13,y=.2+Math.floor(k/7)*.4;
  const group=k===1&&i>=20?'away':k===2&&i===30?'away':p.group;
  return [{id:k+1,box:[x,y,x+.025,y+.06],confidence:.9,appearance:[{rgb:uniforms[group][0],weight:1}]}];
})}));
const data=validateDataset({schema:'fpa-tracks/v1',datasetId:'team-review',video:{name:'synthetic',width:1600,height:900,fps:30,duration:6,clipStart:0,clipEnd:6},detector:{sampleFps:10},frames});
let review={...emptyReview(data),uniforms,roster,setup:{time:0}};
for(let i=0;i<13;i++)review=assign(review,data,i+1,...trackRange(data,i+1),{personId:roster[i].id,source:'manual',locked:i===1||i===2});
const classify=b=>classifyUniform(b.appearance,uniforms),timeline=uniformTimeline(data,uniforms);
const conflicts=lockedTeamConflicts(data,review,timeline,classify);
assert.equal(conflicts.length,1,'Only sustained opposing evidence is reported, not one mixed frame');
assert.equal(conflicts[0].trackId,2);assert.equal(conflicts[0].from,2);assert.equal(conflicts[0].to,6);
const before=JSON.stringify(review),result=reconnect(data,review);
assert.equal(JSON.stringify(review),before,'Detection never changes human assignments');
assert.equal(identityAt({...review,segments:effectiveSegments(review,result)},2,3).personId,'home-1','An explicit full-range lock requires an operator decision');
assert.deepEqual(hydrateRecovery(packRecovery(result,data),data).lockedConflicts,result.lockedConflicts);
const released=releaseTeamConflicts(review,conflicts);
assert.equal(identityAt(released,2,1).personId,'home-1','Non-conflicting human work survives');
assert.equal(identityAt(released,2,3),null);assert.equal(JSON.stringify(review),before);
assert.deepEqual(releaseTeamConflicts(released,conflicts),released,'Repeated release is idempotent');
const next=reconnect(data,released),working={...released,segments:effectiveSegments(released,next)};
assert.notEqual(identityAt(working,2,3)?.team,'home','A released wrong-team lock cannot be silently inherited again');
assert.deepEqual(validateReview(released,data),released,'Released intervals and exclusions round-trip');
assert.equal(confirmScene(review,data,8,1.96,'away-1').checkpoints[0].time,1.9,'A BB that disappears on the next frame is confirmed on its visible observation');
let confirmed=confirmScene(review,data,2,3,'away-1');
assert.equal(confirmed.checkpoints[0].to,3.1);
confirmed=confirmScene(confirmed,data,3,3,'home-2');
assert.equal(confirmed.checkpoints[0].assignments.length,2,'Tagging another player on this frame preserves existing confirmations');
const visible={...confirmed,segments:effectiveSegments(confirmed,{segments:[],masks:[]})};
assert.equal(identityAt(visible,2,3).personId,'away-1');
assert.equal(identityAt(visible,2,3.1).personId,'home-1','The new point does not silently rewrite a full explicit range');
confirmed=confirmScene(confirmed,data,4,3,'home-2');
assert.equal(confirmed.checkpoints[0].assignments.length,2,'A person occupies only one BB at a checkpoint');
assert(!confirmed.checkpoints[0].assignments.some(a=>a.trackId===3));
const cleared=clearScenes(confirmed,2,3,3.1);assert.equal(cleared.checkpoints[0].assignments.length,1);
assert.deepEqual(validateReview(confirmed,data),confirmed);
console.log('PASS: sustained team conflicts, explicit locks, targeted release, recovery cache, immutable reviews, point tagging and same-scene merge/clear.');
