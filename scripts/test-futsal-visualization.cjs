const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('../apps/web/node_modules/typescript');
const mod = { exports: {} };
Function('exports', ts.transpile(fs.readFileSync('apps/web/components/futsal/graphics.ts','utf8'),{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}))(mod.exports);
const {shotPosition,graphics,teamName,safeName}=mod.exports;
assert.deepEqual(shotPosition({shot_x:40,shot_y:0}),{x:0,y:0});
assert.deepEqual(shotPosition({shot_x:20,shot_y:20}),{x:20,y:20});
for(const shot of [{shot_x:null,shot_y:10},{shot_x:41,shot_y:10},{shot_x:30,shot_y:NaN}])assert.equal(shotPosition(shot),null);
const match={id:'test',name:'[CUP] A & B vs C <D>',metadata:{}};
assert.equal(teamName(match,'HOME'),'A & B'); assert.equal(teamName(match,'AWAY'),'C <D>');
const lanes={left_count:3,center_count:1,right_count:0,total_count:4};
const summary={lanes:{home:lanes,away:lanes},possession:{home_ms:60000,away_ms:180000}};
const dom={bins:[{start_ms:0,end_ms:60000,dominance:.5},{start_ms:60000,end_ms:120000,dominance:-.5,annotations:{goal_summary:{away:1}}}],breaks:[]};
const shots=Array.from({length:75},(_,i)=>({id:String(i),type:'XG',team:'HOME',is_goal:i===0,shot_x:34,shot_y:10,xg:.1}));
const cards=graphics(match,shots,summary,dom,{home:'#ff7400',away:'#2158e8',background:'dark'});
assert.equal(cards.length,5); assert(cards[0].svg.includes('75 기록'));assert(cards[0].svg.includes('A &amp; B'));assert(!cards[1].svg.includes('C <D>'));
assert(cards[3].svg.includes('75.0%'));assert(cards[4].svg.includes('25.0%'));assert(cards[4].svg.includes('75.0%'));
assert(cards[2].svg.includes('1분 단위'));assert(!cards[2].svg.includes('HT'));
assert(cards.every(c=>!c.svg.includes('NaN')&&!c.svg.includes('undefined')));
const empty=graphics(match,[],{lanes:{home:{...lanes,total_count:0,left_count:0,center_count:0},away:{...lanes,total_count:0,left_count:0,center_count:0}},possession:{home_ms:0,away_ms:0}},{bins:[]},{home:'#ff7400',away:'#2158e8',background:'transparent'});
assert(empty.every(c=>!c.svg.includes('NaN')&&!c.svg.includes('width="1600" height="1000" fill=')));
assert(!safeName('a/b:c|d').match(/[/:|]/));
console.log('Futsal visualization: coordinate bounds, complete >50 event data, empty data, possession/lane ratios, XML escaping, single-period charts and filenames passed.');
